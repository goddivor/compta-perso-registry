// Writes LOGOS-TODO.md: per type, the brands still without an approved logo, with their countries and
// any candidate source already found — the worklist for manual SVG redrawing. Usage: node scripts/logos/report.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { brandKeyOf } from './brand.mjs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..')
const C = join(ROOT, '.cache/logos')
const cands = JSON.parse(readFileSync(join(C, 'candidates.json'), 'utf8'))
const results = JSON.parse(readFileSync(join(C, 'results.json'), 'utf8'))
// Brands from the CURRENT data only (stale cache keys from older groupings are ignored).
const live = new Map()
for (const f of readdirSync(join(ROOT, 'data/operators')).filter((x) => x.endsWith('.json'))) {
  const doc = JSON.parse(readFileSync(join(ROOT, 'data/operators', f), 'utf8'))
  for (const op of doc.operators) {
    if (op.status === 'defunct') continue
    const k = brandKeyOf(op, doc.country)
    if (!live.has(k)) live.set(k, { key: k, name: op.name, type: op.type, countries: [], operators: [], candidates: cands[k]?.candidates ?? [] })
    live.get(k).countries.push(doc.country); live.get(k).operators.push(op.id)
  }
}
const ORDER = ['mobile_money', 'bank', 'fintech', 'microfinance']
const TITLE = { mobile_money: 'Mobile money', bank: 'Banks', fintech: 'Fintech', microfinance: 'Microfinance' }

let md = '# Logos still missing\n\nGenerated by `scripts/logos/report.mjs` — do not edit by hand.\n' +
  'Each brand needs an SVG: find the official one, or redraw it (`logo.method: "redrawn"`), then add it to\n' +
  '`.cache/logos/results.json` as approved and run `npm run logos:apply`.\n'
for (const type of ORDER) {
  const all = [...live.values()].filter((b) => b.type === type)
  const missing = all.filter((b) => results[b.key]?.review !== 'approved').sort((a, b) => b.operators.length - a.operators.length)
  md += `\n## ${TITLE[type]} — ${all.length - missing.length}/${all.length} brands have a logo\n\n`
  if (type === 'microfinance') { md += `${missing.length} microfinance brands without a logo (list omitted; see candidates.json).\n`; continue }
  md += '| Brand | Countries | Operators | Lead |\n|---|---|---|---|\n'
  for (const b of missing) {
    const lead = results[b.key]?.review === 'rejected' ? 'candidate rejected' : b.candidates[0]?.via ?? '—'
    md += `| ${b.name} | ${[...new Set(b.countries)].join(' ')} | ${b.operators.length} | ${lead} |\n`
  }
}
writeFileSync(join(ROOT, 'LOGOS-TODO.md'), md)
console.log('OK — LOGOS-TODO.md written')
